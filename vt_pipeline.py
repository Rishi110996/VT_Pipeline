#!/usr/bin/env python3
"""
vt_pipeline.py — Main orchestrator for the VirusTotal malware hunting pipeline.

Designed to run via cron (1-2x/week).  For each enabled malware family the
pipeline performs the following steps:

  1. Search VirusTotal Intelligence for new samples
  2. Filter out previously processed hashes
  3. Download samples to external storage
  4. Pre-scan with existing YARA rules to keep only undetected samples
  5. Run androAiV2 LLM analysis on undetected samples
  6. Parse reports and extract generated YARA rules
  7. Build a ZIP artifact (reports + YARA rules)
  8. Create a Zintel case with the artifact attached
  9. Clean up downloaded samples, persist processed hashes

Usage
-----
    python3 vt_pipeline.py                    # normal run
    python3 vt_pipeline.py --dry-run          # skip analysis & case creation
    python3 vt_pipeline.py --config /path/to/config.yaml
    python3 vt_pipeline.py --family cerberus  # process only one family
"""

import argparse
import hashlib
import json
import logging
import os
import shutil
import sys
from datetime import datetime, timezone

import yaml

from modules.vt_search import search_family, download_samples
from modules.yara_scanner import load_rules, scan_samples
from modules.androai_runner import run_analysis
from modules.report_parser import parse_verdicts
from modules.artifact_builder import build_artifact_zip
from modules.zintel_client import ZintelClient
from modules.state_manager import (
    load_processed_hashes,
    save_processed_hashes,
    append_run_history,
)


# ── Helpers ─────────────────────────────────────────────────────────────────

def setup_logging(log_dir: str, level: str = "INFO") -> str:
    """Configure logging to console and a timestamped log file."""
    os.makedirs(log_dir, exist_ok=True)
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    log_file = os.path.join(log_dir, f"pipeline_run_{ts}.log")

    fmt = logging.Formatter(
        "%(asctime)s [%(name)s] %(levelname)s — %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )
    fh = logging.FileHandler(log_file, encoding="utf-8")
    fh.setFormatter(fmt)
    ch = logging.StreamHandler(sys.stdout)
    ch.setFormatter(fmt)

    root = logging.getLogger()
    root.setLevel(getattr(logging, level.upper(), logging.INFO))
    root.addHandler(fh)
    root.addHandler(ch)
    return log_file


def load_config(config_path: str) -> dict:
    """Load and validate the YAML configuration file."""
    with open(config_path, "r") as fh:
        cfg = yaml.safe_load(fh)
    assert "pipeline" in cfg, "Missing 'pipeline' section in config"
    assert "paths" in cfg, "Missing 'paths' section in config"
    assert "malware_families" in cfg, "Missing 'malware_families' in config"
    return cfg


def build_family_researcher_map(cfg: dict) -> dict:
    """Return ``{family_name: {id, name, email}}`` from the researchers config."""
    mapping = {}
    for researcher in cfg.get("researchers", []):
        for family in researcher.get("families", []):
            mapping[family.lower()] = {
                "id": researcher["id"],
                "name": researcher.get("name", ""),
                "email": researcher.get("email", ""),
            }
    return mapping


def compute_md5(filepath: str) -> str:
    """Compute MD5 hash of a file."""
    h = hashlib.md5()
    with open(filepath, "rb") as f:
        for chunk in iter(lambda: f.read(8192), b""):
            h.update(chunk)
    return h.hexdigest()


def build_case_comments(family, parsed_verdicts, scan_summary):
    """Build a rich comment string for the Zintel case."""
    lines = [
        "Auto-generated by VT Pipeline",
        "",
        f"Family: {family}",
        f"Date: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}",
        f"Samples analysed: {len(parsed_verdicts)}",
        f"Malicious: {sum(1 for v in parsed_verdicts if v.get('is_malicious'))}",
        f"YARA rules generated: {sum(1 for v in parsed_verdicts if v.get('yara_rule'))}",
        "",
        "--- Pre-scan Summary ---",
        f"Downloaded from VT: {scan_summary.get('downloaded', 'N/A')}",
        f"Already detected by YARA: {scan_summary.get('yara_detected', 'N/A')}",
        f"Undetected (analysed): {scan_summary.get('undetected', 'N/A')}",
        "",
        "--- Sample Verdicts ---",
    ]
    for v in parsed_verdicts:
        status = "MALICIOUS" if v.get("is_malicious") else "CLEAN"
        risk = v.get("risk_score", 0)
        cat = v.get("category", "")
        yara_tag = " [YARA]" if v.get("yara_rule") else ""
        snippet = (v.get("summary", "") or "")[:150]
        lines.append(f"  {v['sha256'][:16]}... — {status} Risk:{risk} {cat}{yara_tag}")
        if snippet:
            lines.append(f"    {snippet}...")
    return "\n".join(lines)


# ── Per-family processing ───────────────────────────────────────────────────

def process_family(family_cfg, cfg, processed_hashes, researcher_map,
                   zintel, compiled_yara_rules, dry_run=False):
    """Run the full pipeline for a single malware family."""
    logger = logging.getLogger("vt_pipeline")
    family = family_cfg["name"]
    paths = cfg["paths"]
    pcfg = cfg["pipeline"]

    logger.info("=" * 70)
    logger.info("PROCESSING FAMILY: %s", family.upper())
    logger.info("=" * 70)

    entry = {
        "family": family, "vt_query": family_cfg["vt_query"],
        "vt_results": 0, "already_processed": 0, "downloaded": 0,
        "download_failed": 0, "yara_detected": 0, "undetected_analysed": 0,
        "malicious_verdicts": 0, "yara_rules_generated": 0,
        "zintel_case_id": None, "assigned_to": None, "errors": [],
    }

    # 2a — VT Search
    vt_cli = cfg["virustotal"]["vt_cli_path"]
    results = search_family(vt_cli, family_cfg["vt_query"],
                            limit=pcfg.get("max_samples_per_family", 20))
    entry["vt_results"] = len(results)
    if not results:
        logger.warning("No VT results for '%s'", family); return entry

    new = [r for r in results if r["sha256"] not in processed_hashes]
    entry["already_processed"] = len(results) - len(new)
    if not new:
        logger.info("All VT results already processed for '%s'", family)
        return entry

    # 2b — Download
    family_dir = os.path.join(paths["sample_download_dir"], family)
    dl = download_samples(vt_cli, [r["sha256"] for r in new], family_dir)
    ok_dl = [r for r in dl if r["success"]]
    entry["downloaded"], entry["download_failed"] = len(ok_dl), len(dl)-len(ok_dl)
    if not ok_dl:
        entry["errors"].append("all downloads failed"); return entry
    sha_to_md5 = {r["sha256"]: r.get("md5", "") for r in new}

    # 2c — YARA Pre-Scan
    scan = scan_samples(compiled_yara_rules, [r["path"] for r in ok_dl])
    detected, undetected = scan["detected"], scan["undetected"]
    entry["yara_detected"] = len(detected)
    for d in detected:
        try: os.remove(d["path"])
        except OSError: pass
    if not undetected:
        for r in dl: processed_hashes.add(r["sha256"])
        return entry
    target = pcfg.get("samples_per_case", 10)
    if len(undetected) > target:
        for e2 in undetected[target:]:
            try: os.remove(e2["path"])
            except OSError: pass
        undetected = undetected[:target]
    entry["undetected_analysed"] = len(undetected)
    scan_summary = {"downloaded": len(ok_dl), "yara_detected": len(detected),
                    "undetected": len(undetected)}

    if dry_run:
        logger.info("[DRY RUN] Skipping analysis for '%s'", family)
        for r in dl: processed_hashes.add(r["sha256"])
        return entry

    # Continued in _process_family_analysis
    return _process_family_analysis(
        family, family_dir, cfg, pcfg, paths, entry, dl,
        sha_to_md5, scan_summary, researcher_map, zintel,
        processed_hashes,
    )


def _process_family_analysis(family, family_dir, cfg, pcfg, paths, entry,
                              dl, sha_to_md5, scan_summary, researcher_map,
                              zintel, processed_hashes):
    """Steps 2d-2h: analysis, report parsing, case creation, cleanup."""
    logger = logging.getLogger("vt_pipeline")

    # 2d — androAiV2 Analysis
    report_dir = os.path.join(family_dir, "report")
    analysis = run_analysis(
        androai_root=paths["androai_root"],
        androai_script=paths["androai_script"],
        venv_python=paths["androai_venv_python"],
        sample_dir=family_dir, report_dir=report_dir,
        lease_hours=pcfg.get("lease_hours", 0.25),
    )
    if not analysis["success"]:
        entry["errors"].append(f"analysis failed: exit={analysis['exit_code']}")
        for r in dl: processed_hashes.add(r["sha256"])
        return entry

    # 2e — Parse Reports
    verdicts = parse_verdicts(report_dir)
    entry["malicious_verdicts"] = sum(1 for v in verdicts if v.get("is_malicious"))
    entry["yara_rules_generated"] = sum(1 for v in verdicts if v.get("yara_rule"))
    if not verdicts:
        entry["errors"].append("no verdicts produced")
        for r in dl: processed_hashes.add(r["sha256"])
        return entry

    # 2f — Build Artifact ZIP
    artifact_zip = build_artifact_zip(
        family=family, parsed_verdicts=verdicts, report_dir=report_dir,
        output_dir=os.path.join(paths["pipeline_data_dir"], "artifacts"),
        run_metadata={"vt_query": entry["vt_query"], "scan_summary": scan_summary},
    )

    # 2g — Create Zintel Case
    researcher = researcher_map.get(family.lower())
    assign_to = researcher["id"] if researcher else cfg["researchers"][0]["id"]
    entry["assigned_to"] = assign_to

    md5_list = []
    for v in verdicts:
        md5 = sha_to_md5.get(v["sha256"], "")
        if not md5:
            sp = os.path.join(family_dir, v["sha256"])
            if os.path.isfile(sp): md5 = compute_md5(sp)
        if md5: md5_list.append(md5)

    date_str = datetime.now(timezone.utc).strftime("%Y-%m-%d_%H%M%S")
    case_name = f"VT Pipeline - {family.capitalize()} - {date_str}"
    comments = build_case_comments(family, verdicts, scan_summary)

    cr = zintel.create_case(
        name=case_name, source_id=cfg["zintel"]["source_id"],
        comments=comments, assign_to=assign_to,
        assignment_type=cfg["zintel"].get("assignment_type", "user"),
        associated_md5s=md5_list, artifact_path=artifact_zip,
    )
    if cr["success"]:
        entry["zintel_case_id"] = cr["case_id"]
        logger.info("Zintel case: %s (id=%s)", case_name, cr["case_id"])
    else:
        entry["errors"].append(f"case creation failed: {cr['message']}")

    # 2h — Cleanup
    for r in dl: processed_hashes.add(r["sha256"])
    logger.info("Cleaning up %s", family_dir)
    for fname in os.listdir(family_dir):
        fp = os.path.join(family_dir, fname)
        if os.path.isfile(fp):
            try: os.remove(fp)
            except OSError: pass
    shutil.rmtree(report_dir, ignore_errors=True)
    try:
        if os.path.isdir(family_dir) and not os.listdir(family_dir):
            os.rmdir(family_dir)
    except OSError: pass

    logger.info("Family '%s' complete", family)
    return entry


# ── Main ────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="VT Pipeline")
    parser.add_argument("--config", "-c",
        default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "config.yaml"))
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--family", type=str, default=None,
        help="Process only this family (overrides enabled/disabled)")
    args = parser.parse_args()

    cfg = load_config(args.config)
    paths = cfg["paths"]
    pcfg = cfg["pipeline"]
    dry_run = args.dry_run or pcfg.get("dry_run", False)

    log_file = setup_logging(paths.get("pipeline_logs_dir", "logs"),
                             pcfg.get("log_level", "INFO"))
    logger = logging.getLogger("vt_pipeline")
    logger.info("VT Pipeline starting — config=%s log=%s", args.config, log_file)
    if dry_run:
        logger.info("*** DRY RUN MODE ***")

    data_dir = paths.get("pipeline_data_dir", "data")
    os.makedirs(data_dir, exist_ok=True)
    processed_hashes = load_processed_hashes(data_dir)
    researcher_map = build_family_researcher_map(cfg)
    logger.info("Researcher map: %s",
                json.dumps({k: v["name"] for k, v in researcher_map.items()}))

    compiled_yara = load_rules(paths.get("yara_scan_file", ""),
                               paths.get("llm_generated_yara_dir", ""))
    logger.info("YARA rule sets loaded: %d", len(compiled_yara))

    zintel = ZintelClient(
        api_url=cfg.get("zintel", {}).get("api_url", ""),
        api_key=cfg.get("zintel", {}).get("api_key", ""),
    )

    families = cfg.get("malware_families", [])
    if args.family:
        families = [f for f in families if f["name"].lower() == args.family.lower()]
        if not families:
            logger.error("Family '%s' not in config", args.family); sys.exit(1)
        for f in families: f["enabled"] = True

    enabled = [f for f in families if f.get("enabled", False)]
    if not enabled:
        logger.warning("No enabled families"); sys.exit(0)
    logger.info("Families: %s", ", ".join(f["name"] for f in enabled))

    run_entries = []
    for fc in enabled:
        try:
            run_entries.append(process_family(
                fc, cfg, processed_hashes, researcher_map,
                zintel, compiled_yara, dry_run))
        except Exception:
            logger.exception("Error processing '%s'", fc["name"])
            run_entries.append({"family": fc["name"], "errors": ["unhandled exception"]})
        save_processed_hashes(data_dir, processed_hashes)

    for e in run_entries:
        append_run_history(data_dir, e)

    logger.info("=" * 70)
    logger.info("VT Pipeline complete")
    for e in run_entries:
        cid = e.get("zintel_case_id")
        if cid:
            logger.info("  %s: case=%s mal=%d yara=%d", e["family"], cid,
                        e.get("malicious_verdicts",0), e.get("yara_rules_generated",0))
        elif e.get("errors"):
            logger.info("  %s: ERRORS: %s", e["family"], "; ".join(e["errors"]))
        else:
            logger.info("  %s: vt=%d, no case", e["family"], e.get("vt_results",0))
    logger.info("=" * 70)


if __name__ == "__main__":
    main()
